defmodule Theme1.Clocks do
  @moduledoc """
  Records clock-in/clock-out events, whether sent live or replayed later from
  the mobile app's offline outbox.

  * Idempotency: the client sends one `idempotency_key` per action. A replay of
    the same key returns the original event instead of clocking twice.
  * Trusted time: an offline event carries the `device_time` at which the user
    actually clocked. It is used only when plausible (not in the future, not
    too old, and consistent with the user's sessions). Otherwise the reception
    time is used and the working time is flagged for manager review.

  Every event is journaled in the `clocks` table with its time source.
  """

  alias Theme1.{Clock, Repo, TimeTracking}

  # Oldest offline event accepted with its own time.
  @max_offline_age_seconds 72 * 3600
  # Tolerated clock drift for a device slightly ahead of the server.
  @max_future_skew_seconds 120

  @type action :: :in | :out

  @doc """
  Record a clock action for `user`.

  Options:
    * `:idempotency_key` - unique per action, generated by the client
    * `:device_time` - ISO 8601 time of an offline action, honoured only when `:trust_device_time` is true
    * `:trust_device_time` - false when someone clocks on behalf of another user

  Returns `{:ok, working_time, clock}`, `{:ok, :duplicate, clock}` or `{:error, reason}`.
  """
  def record_clock(%Theme1.User{} = user, action, opts \\ []) when action in [:in, :out] do
    key = blank_to_nil(opts[:idempotency_key])

    case key && Repo.get_by(Clock, user_id: user.id, idempotency_key: key) do
      %Clock{} = existing -> {:ok, :duplicate, existing}
      _ -> apply_clock(user, action, key, opts)
    end
  end

  defp apply_clock(user, action, key, opts) do
    received_at = now()
    device_time = if opts[:trust_device_time], do: parse_time(opts[:device_time]), else: nil
    {time, source} = resolve_time(user.id, action, device_time, received_at)
    time = ensure_after_session_start(user.id, action, time)

    Repo.transaction(fn ->
      with {:ok, working_time} <- clock(user, action, time),
           {:ok, working_time} <- flag_rejected_device_time(working_time, device_time, source),
           {:ok, event} <- insert_event(user, action, key, time, source, received_at, device_time) do
        {working_time, event}
      else
        {:error, reason} -> Repo.rollback(reason)
      end
    end)
    |> case do
      {:ok, {working_time, event}} -> {:ok, working_time, event}
      {:error, %Ecto.Changeset{} = changeset} -> maybe_duplicate(user, key, changeset)
      {:error, reason} -> {:error, reason}
    end
  end

  defp clock(user, :in, time), do: TimeTracking.clock_in(user, time)
  defp clock(user, :out, time), do: TimeTracking.clock_out(user, time)

  # An offline time we could not trust: the session uses the reception time, so a manager should check it.
  defp flag_rejected_device_time(working_time, device_time, "server") when not is_nil(device_time) do
    working_time |> Ecto.Changeset.change(needs_review: true) |> Repo.update()
  end

  defp flag_rejected_device_time(working_time, _device_time, _source), do: {:ok, working_time}

  defp insert_event(user, action, key, time, source, received_at, device_time) do
    %Clock{}
    |> Clock.record_changeset(%{
      user_id: user.id,
      status: action == :in,
      time: time,
      time_source: source,
      received_at: received_at,
      device_time: device_time,
      idempotency_key: key
    })
    |> Repo.insert()
  end

  # Two concurrent replays of the same key: the loser reports the winner's event.
  defp maybe_duplicate(user, key, changeset) do
    with true <- not is_nil(key) and Keyword.has_key?(changeset.errors, :user_id),
         %Clock{} = existing <- Repo.get_by(Clock, user_id: user.id, idempotency_key: key) do
      {:ok, :duplicate, existing}
    else
      _ -> {:error, changeset}
    end
  end

  ## Trusted time

  defp resolve_time(_user_id, _action, nil, received_at), do: {received_at, "server"}

  defp resolve_time(user_id, action, device_time, received_at) do
    if plausible?(user_id, action, device_time, received_at) do
      # A device a little ahead of the server never produces a future time.
      {earliest(device_time, received_at), "device"}
    else
      {received_at, "server"}
    end
  end

  defp plausible?(user_id, action, device_time, received_at) do
    age = DateTime.diff(received_at, device_time, :second)

    age >= -@max_future_skew_seconds and
      age <= @max_offline_age_seconds and
      consistent_with_sessions?(user_id, action, device_time)
  end

  # A clock-in cannot precede the last closed session; a clock-out cannot precede its own start.
  defp consistent_with_sessions?(user_id, :in, device_time) do
    case TimeTracking.last_session_end(user_id) do
      nil -> true
      last_end -> DateTime.compare(device_time, last_end) != :lt
    end
  end

  defp consistent_with_sessions?(user_id, :out, device_time) do
    case TimeTracking.open_session_start(user_id) do
      nil -> true
      start -> DateTime.compare(device_time, start) == :gt
    end
  end

  # An offline in/out pair replayed within the same second, with an untrusted
  # device time, would give end == start and be rejected, blocking the outbox.
  # Keep the clock-out strictly after the start; it is flagged for review anyway.
  defp ensure_after_session_start(user_id, :out, time) do
    case TimeTracking.open_session_start(user_id) do
      nil -> time
      start -> if DateTime.compare(time, start) == :gt, do: time, else: DateTime.add(start, 1)
    end
  end

  defp ensure_after_session_start(_user_id, :in, time), do: time

  ## Helpers

  defp parse_time(value) when is_binary(value) do
    case DateTime.from_iso8601(value) do
      {:ok, datetime, _offset} -> DateTime.truncate(datetime, :second)
      _ -> nil
    end
  end

  defp parse_time(_value), do: nil

  defp earliest(a, b), do: if(DateTime.compare(a, b) == :gt, do: b, else: a)

  defp now, do: DateTime.utc_now() |> DateTime.truncate(:second)

  defp blank_to_nil(value) when value in [nil, ""], do: nil
  defp blank_to_nil(value) when is_binary(value), do: String.slice(value, 0, 100)
  defp blank_to_nil(_value), do: nil
end
